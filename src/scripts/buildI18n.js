#!/usr/bin/env node
// Builds public/i18n/<lang>.js from src-frontend/i18n/<lang>/*.json.
// Each JSON file: { "text": {..}, "html": {..}, "patterns": [{ "re": "...", "es": "..." }] }
//
// Scope: a file named after a page in public/ (dashboard.json -> dashboard.html) only applies
// on that page, and wins over the shared entries there. Every other file (common.json,
// server.json, flow-editor.json...) is shared by all pages. Within one scope, a key defined
// twice with different values fails the build.
// Usage: node src/scripts/buildI18n.js   (npm run build:i18n)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const srcDir = path.join(root, 'src-frontend', 'i18n');
const outDir = path.join(root, 'public', 'i18n');
const norm = (s) => String(s).replace(/\s+/g, ' ').trim();
const pages = new Set(fs.readdirSync(path.join(root, 'public')).filter((f) => f.endsWith('.html')).map((f) => f.slice(0, -5)));

let failed = false;
fs.mkdirSync(outDir, { recursive: true });
for (const lang of fs.readdirSync(srcDir).filter((d) => fs.statSync(path.join(srcDir, d)).isDirectory())) {
  const scopes = {}; // '' = shared, else page name
  const scope = (name) => (scopes[name] ||= { text: {}, html: {}, patterns: [], from: { text: {}, html: {} }, re: new Set() });
  const files = fs.readdirSync(path.join(srcDir, lang)).filter((f) => f.endsWith('.json')).sort();
  for (const f of files) {
    let data;
    try { data = JSON.parse(fs.readFileSync(path.join(srcDir, lang, f), 'utf8')); } catch (e) {
      console.error(`[i18n] ${lang}/${f}: invalid JSON: ${e.message}`); failed = true; continue;
    }
    const page = f.slice(0, -5);
    const s = scope(pages.has(page) ? page : '');
    for (const kind of ['text', 'html']) {
      for (const [k, v] of Object.entries(data[kind] || {})) {
        const key = norm(k);
        if (!key || typeof v !== 'string') continue;
        if (key in s[kind] && s[kind][key] !== v) {
          console.error(`[i18n] ${lang}: "${key}" is "${s[kind][key]}" in ${s.from[kind][key]} but "${v}" in ${f}`);
          failed = true; continue;
        }
        s[kind][key] = v; s.from[kind][key] = f;
      }
    }
    for (const p of data.patterns || []) {
      try { new RegExp(p.re); } catch (e) { console.error(`[i18n] ${lang}/${f}: bad pattern ${p.re}`); failed = true; continue; }
      if (s.re.has(p.re)) continue;
      s.re.add(p.re);
      s.patterns.push({ re: p.re, es: p.es });
    }
  }
  const pack = (s) => ({ text: s.text, html: s.html, patterns: s.patterns });
  const out = { ...pack(scope('')), pages: {} };
  for (const [name, s] of Object.entries(scopes)) if (name) out.pages[name] = pack(s);
  const body = `// Generated by src/scripts/buildI18n.js from src-frontend/i18n/${lang}/. Do not edit.\n`
    + `window.AIORC_I18N = window.AIORC_I18N || {};\nwindow.AIORC_I18N.${lang} = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(outDir, `${lang}.js`), body);
  const count = (s) => `${Object.keys(s.text).length} texts, ${Object.keys(s.html).length} html, ${s.patterns.length} patterns`;
  console.log(`[i18n] ${lang} shared: ${count(scope(''))}`);
  for (const [name, s] of Object.entries(scopes)) if (name) console.log(`[i18n] ${lang} ${name}: ${count(s)}`);
}
if (failed) process.exit(1);
